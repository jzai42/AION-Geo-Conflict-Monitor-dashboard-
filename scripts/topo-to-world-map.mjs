import { readFileSync, writeFileSync } from 'node:fs';

const topo = JSON.parse(
  readFileSync(
    '/Users/jeremy/.cursor/projects/Users-jeremy-AION-Geo-Conflict-Monitor-dashboard/agent-tools/5b14f011-06a6-43c0-bd52-257d5b8a3574.txt',
    'utf8',
  ),
);

const { scale, translate } = topo.transform;
const decoded = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indices) {
  const pts = [];
  for (const idx of indices) {
    const rev = idx < 0;
    const arc = decoded[rev ? ~idx : idx];
    const seq = rev ? [...arc].reverse() : arc;
    for (let i = pts.length ? 1 : 0; i < seq.length; i++) pts.push(seq[i]);
  }
  return pts;
}

function toXY([lon, lat]) {
  return [((lon + 180) / 360) * 1000, ((90 - lat) / 180) * 500];
}

const geoms = topo.objects.land.geometries;
const paths = [];
for (const g of geoms) {
  for (const poly of g.arcs) {
    const d = poly
      .map((indices) => {
        const pts = ring(indices).map(toXY);
        if (pts.length < 3) return '';
        return `M${pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L')}Z`;
      })
      .join('');
    if (d) paths.push(d);
  }
}

